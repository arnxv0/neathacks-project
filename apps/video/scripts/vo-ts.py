#!/usr/bin/env python3
"""Regenerate src/data/vo.ts from public/vo/durations.json (mp3 lengths) and the narration text in narrate.py.

The square explainer and the teasers burn the narration in as captions, so the text must come from the same dict the
audio was synthesized from. Run after narrate.py + the wav->mp3 conversion: `python3 apps/video/scripts/vo-ts.py`.
"""
import json, pathlib, re
here = pathlib.Path(__file__).resolve().parent
video = here.parent
durs = json.load(open(video / "public" / "vo" / "durations.json"))
src = (here / "narrate.py").read_text()
body = src[src.index("lines = {"): src.index("\n}\n", src.index("lines = {"))]
lines = dict(re.findall(r'^\s*"([a-z0-9-]+)":\s*"((?:[^"\\]|\\.)*)",?\s*$', body, flags=re.M))
missing = set(lines) - set(durs)
assert not missing, f"no duration for {sorted(missing)}; run narrate.py"
out = ["// generated by scripts/vo-ts.py from public/vo/durations.json and the narration in scripts/narrate.py", "export const VO: Record<string, number> = {"]
out += [f"  {json.dumps(k)}: {v}," for k, v in durs.items()]
out += ["};", "", "// narration text per clip, burned in as captions in the square explainer and the teasers", "export const LINES: Record<string, string> = {"]
out += [f"  {json.dumps(k)}: {json.dumps(v)}," for k, v in lines.items()]
out += ["};", ""]
(video / "src" / "data" / "vo.ts").write_text("\n".join(out))
print(f"vo.ts: {len(durs)} durations, {len(lines)} lines")
