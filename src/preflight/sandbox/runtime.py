"""Run a sandbox target. Third-party code is only ever started inside a Docker container; without Docker the start is
refused unless the owner marked the target `trusted` AND set PREFLIGHT_ALLOW_UNSANDBOXED=1.

Network choice (documented in docs/SANDBOX_TARGETS.md): the container sits on Docker's default bridge with outbound
access, because the agent has to reach the model gateway (a remote HTTPS endpoint) and the chaos proxy on the host
(`host.docker.internal`). Nothing is mounted from the host, the port is published on 127.0.0.1 only, and
PREFLIGHT_SANDBOX_NETWORK can name a stricter user-defined network (for example one with an egress proxy).
"""
from __future__ import annotations
import json, os, pathlib, re, secrets, shutil, socket, subprocess, tempfile, time
from dataclasses import dataclass
import httpx
from .. import config
from ..target import process
from ..target.loader import SystemSpec
from . import contract, registry
from .registry import Entry, RegistryError

BUILD_TIMEOUT_S = 900
HARDENING = ["--memory", "1g", "--cpus", "1", "--pids-limit", "256", "--cap-drop", "ALL", "--security-opt", "no-new-privileges"]
HOST_ALIAS = "host.docker.internal"
DEFAULT_TARGET_MODEL = "claude-haiku"     # same default as the built-in target's .env.example
_PROCS: dict[str, subprocess.Popen] = {}
_docker_cache: tuple[float, bool] | None = None

PY_DOCKERFILE = """# generated by Preflight for a sandbox target; lives outside the clone and is never committed to it
FROM python:3.12-slim
ENV PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1 PIP_DISABLE_PIP_VERSION_CHECK=1 PYTHONPATH=/app:/app/src HOME=/tmp
WORKDIR /app
COPY . /app
RUN pip install --no-cache-dir uv \\
 && if [ -f requirements.txt ]; then uv pip install --system --no-cache -r requirements.txt; fi \\
 && if [ -f pyproject.toml ]; then uv pip install --system --no-cache -r pyproject.toml; fi \\
 && uv pip install --system --no-cache fastapi "uvicorn[standard]" httpx pyyaml
RUN useradd --create-home --uid 10001 sbx && chown -R sbx /app
USER sbx
"""
NODE_DOCKERFILE = """# generated by Preflight for a sandbox target; lives outside the clone and is never committed to it
FROM node:22-slim
ENV NODE_ENV=production HOME=/tmp
WORKDIR /app
COPY . /app
RUN if [ -f package-lock.json ]; then npm ci --ignore-scripts; else npm install --ignore-scripts; fi && chown -R node /app
USER node
"""

@dataclass
class Running:
    slug: str
    mode: str                 # docker | process
    port: int
    base_url: str
    spec: SystemSpec
    container: str | None = None
    reused: bool = False

# ---- names, ports, per-target state ----
def _safe(slug: str) -> str:
    return re.sub(r"[._]+", "-", registry.check_slug(slug)).strip("-")

def image_name(slug: str, instance: str | None = None) -> str:
    return f"preflight-sbx-{_safe(slug)}" + (f":{instance}" if instance else "")

def container_name(slug: str, instance: str | None = None) -> str:
    return f"preflight-sbx-{_safe(slug)}" + (f"-{instance}" if instance else "")

def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]

def _port_free(port: int) -> bool:
    with socket.socket() as s:
        try:
            s.bind(("127.0.0.1", port)); return True
        except OSError:
            return False

def _state(slug: str) -> dict:
    p = registry.meta_path(slug, ".runtime.json")
    try:
        return json.loads(p.read_text()) if p.is_file() else {}
    except Exception:
        return {}

def _save_state(slug: str, st: dict) -> None:
    p = registry.meta_path(slug, ".runtime.json")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(st, indent=2))
    os.chmod(p, 0o600)        # holds the per-target ownership token

def _is_ours(port: int, token: str) -> bool:
    try:
        return httpx.get(f"http://127.0.0.1:{port}/preflight-verify", timeout=2).json().get("ownership_token") == token
    except Exception:
        return False

def resolve(slug: str) -> dict[str, str]:
    """The `${PORT}` / `${PREFLIGHT_OWNERSHIP_TOKEN}` values this target's manifest is loaded with. The token is random
    per target; the port is sticky while it is free or still held by this target's own instance. Starts nothing."""
    registry.get(slug)
    st = _state(slug)
    changed = False
    if not st.get("token"):
        st["token"] = secrets.token_urlsafe(24); changed = True
    if not st.get("port") or not (_port_free(st["port"]) or _is_ours(st["port"], st["token"])):
        st["port"] = free_port(); changed = True
    if changed:
        _save_state(slug, st)
    return {"PORT": str(st["port"]), "PREFLIGHT_OWNERSHIP_TOKEN": st["token"]}

# ---- gates ----
def require_ready(entry: Entry) -> None:
    """A target may run only after a human approved exactly the files that are on disk now."""
    if entry.status != "ready":
        raise RegistryError(f"{entry.slug} is `{entry.status}`, not approved; review the generated files and approve it first", "not_approved")
    if entry.approved_fingerprint != contract.fingerprint(registry.clone_dir(entry.slug)):
        registry.set_status(entry.slug, "needs_review", note="files changed after approval; review again")
        raise RegistryError(f"{entry.slug}: files changed after approval; review and approve again", "not_approved")

def docker_available(refresh: bool = False) -> bool:
    global _docker_cache
    if _docker_cache and not refresh and time.time() - _docker_cache[0] < 30:
        return _docker_cache[1]
    ok = False
    if shutil.which("docker"):
        try:
            ok = subprocess.run(["docker", "info", "--format", "{{.ServerVersion}}"], capture_output=True, timeout=10).returncode == 0
        except Exception:
            ok = False
    _docker_cache = (time.time(), ok)
    return ok

def unsandboxed_allowed(entry: Entry) -> bool:
    return bool(entry.trusted) and os.getenv("PREFLIGHT_ALLOW_UNSANDBOXED") == "1"

def choose_mode(entry: Entry) -> str:
    if docker_available():
        return "docker"
    if unsandboxed_allowed(entry):
        return "process"
    raise RegistryError("Docker is not available, and third-party code is never started outside a container. Start Docker, or, for a "
                        "repository you own, mark the target trusted and set PREFLIGHT_ALLOW_UNSANDBOXED=1.", "docker_unavailable")

# ---- environment handed to the target ----
def _containerize(url: str) -> str:
    """localhost in a URL means the host, which a container reaches as host.docker.internal."""
    return re.sub(r"(?<=://)(localhost|127\.0\.0\.1)(?=[:/]|$)", HOST_ALIAS, url)

def target_env(spec: SystemSpec, port: int, token: str, *, in_container: bool) -> dict[str, str]:
    """The complete, closed list of variables a sandbox target receives. No other host variable is passed."""
    proxy = f"http://{HOST_ALIAS if in_container else '127.0.0.1'}:{config.CFG.ports.get('proxy', 8300)}"
    base = os.getenv("LITELLM_BASE_URL", "")
    env = {
        "PORT": str(port), "HOST": "0.0.0.0" if in_container else "127.0.0.1", "PREFLIGHT_OWNERSHIP_TOKEN": token,
        "PREFLIGHT_MIRROR_DIR": "/tmp/preflight-mirror",
        "LITELLM_BASE_URL": _containerize(base) if in_container else base,
        # a separate, budget-capped key for third-party code is preferred over Preflight's own
        "LITELLM_API_KEY": os.getenv("PREFLIGHT_SANDBOX_LITELLM_API_KEY") or os.getenv("LITELLM_API_KEY", ""),
        "TARGET_MODEL": os.getenv("PREFLIGHT_SANDBOX_TARGET_MODEL") or os.getenv("TARGET_MODEL", "") or DEFAULT_TARGET_MODEL,
    }
    for comp in spec.components.values():
        for ann in comp.tools.values():
            if ann.upstream_env:
                env[ann.upstream_env] = proxy          # upstream calls go through the chaos proxy
    return {k: v for k, v in env.items() if v}

# ---- docker ----
def dockerfile_for(slug: str, source: pathlib.Path) -> tuple[pathlib.Path, bool]:
    """(dockerfile, generated). The repo's own Dockerfile is used when present; otherwise a minimal one is written next
    to the registry entry, with a matching .dockerignore so the repo's own ignore file cannot hide the adapter."""
    for name in ("Dockerfile", "dockerfile", "Containerfile"):
        p = source / name
        if p.is_file() and not p.is_symlink():
            return p, False
    is_node = (source / "package.json").is_file() and not any((source / n).is_file() for n in ("pyproject.toml", "requirements.txt", "setup.py", "preflight_adapter.py"))
    path = registry.meta_path(slug, ".Dockerfile")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(NODE_DOCKERFILE if is_node else PY_DOCKERFILE)
    registry.meta_path(slug, ".Dockerfile.dockerignore").write_text(".git\n.venv\nnode_modules\n__pycache__\n.env\n.env.*\n")
    return path, True

def build_argv(image: str, dockerfile: pathlib.Path, source: pathlib.Path) -> list[str]:
    return ["docker", "build", "-q", "-f", str(dockerfile), "-t", image, str(source)]

def run_argv(name: str, image: str, port: int, env_names: list[str], start: str, network: str | None = None) -> list[str]:
    """`docker run` for a sandbox target. No volumes, no host network, no privileges; the only published port is on
    loopback; variables are passed by NAME (`-e VAR`), so secrets never appear in the process list."""
    argv = ["docker", "run", "-d", "--rm", "--name", name, "--network", network or os.getenv("PREFLIGHT_SANDBOX_NETWORK") or "bridge",
            "--add-host", f"{HOST_ALIAS}:host-gateway", "-p", f"127.0.0.1:{port}:{port}", *HARDENING]
    for n in sorted(env_names):
        argv += ["-e", n]
    return argv + ["--entrypoint", "sh", image, "-c", start]

def _docker(argv: list[str], timeout: int, env: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(argv, capture_output=True, text=True, timeout=timeout, env=env, stdin=subprocess.DEVNULL)

def _start_docker(slug: str, spec: SystemSpec, source: pathlib.Path, port: int, token: str, instance: str | None) -> str:
    image, name = image_name(slug, instance), container_name(slug, instance)
    dockerfile, _ = dockerfile_for(slug, source)
    try:
        b = _docker(build_argv(image, dockerfile, source), BUILD_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        raise RegistryError(f"docker build timed out after {BUILD_TIMEOUT_S}s", "build_failed")
    if b.returncode != 0:
        raise RegistryError(f"docker build failed:\n{(b.stderr or b.stdout)[-1500:]}", "build_failed")
    _docker(["docker", "rm", "-f", name], 30)
    env = target_env(spec, port, token, in_container=True)
    r = _docker(run_argv(name, image, port, list(env), spec.entry.start or ""), 60, env={**os.environ, **env})
    if r.returncode != 0:
        raise RegistryError(f"docker run failed: {(r.stderr or r.stdout)[-800:]}", "start_failed")
    deadline = time.time() + 90
    while time.time() < deadline:
        if process.healthy(spec.entry, timeout=2):
            return name
        if not _docker(["docker", "ps", "-q", "-f", f"name=^{name}$"], 15).stdout.strip():
            break
        time.sleep(1)
    logs = _docker(["docker", "logs", "--tail", "60", name], 15)
    _docker(["docker", "rm", "-f", name], 30)
    raise RegistryError(f"target did not become healthy at {spec.entry.healthcheck}:\n{(logs.stdout + logs.stderr)[-1500:]}", "start_failed")

def _start_process(slug: str, spec: SystemSpec, source: pathlib.Path, port: int, token: str, key: str) -> None:
    """Trusted fallback: the manifest's `start` command on the host through target/process.py, with the same closed env."""
    env = target_env(spec, port, token, in_container=False)
    env["PREFLIGHT_MIRROR_DIR"] = tempfile.mkdtemp(prefix="preflight-sbx-mirror-")
    env.update({k: os.environ[k] for k in ("PATH", "HOME", "LANG", "TMPDIR") if k in os.environ}, PYTHONDONTWRITEBYTECODE="1")
    comp = spec.entry.model_copy(update={"repo_path": source})
    proc = process.ensure_running(comp, log_path=registry.meta_path(slug, ".target.log"), env=env)
    if proc is not None:
        _PROCS[key] = proc

# ---- public ----
def start(slug: str, source_dir: pathlib.Path | None = None, instance: str | None = None) -> Running:
    """Ensure the approved target is running and return its endpoints as a loaded SystemSpec.
    `source_dir` + `instance` start a second copy from a fix worktree on its own port (replays under --allow-fix)."""
    entry = registry.get(slug)
    require_ready(entry)
    clone = registry.clone_dir(slug)
    env = resolve(slug)
    if instance:
        env = {**env, "PORT": str(free_port())}
    port, token = int(env["PORT"]), env["PREFLIGHT_OWNERSHIP_TOKEN"]
    spec, problems = contract.check(clone, env)     # always the approved manifest from the clone, never a worktree's
    if spec is None or problems:
        raise RegistryError(f"{slug}: preflight.yaml is not valid: " + "; ".join(problems), "invalid_manifest")
    base = f"http://127.0.0.1:{port}"
    if not instance and _is_ours(port, token):
        st = _state(slug)
        if st.get("fingerprint") == entry.approved_fingerprint:
            return Running(slug, st.get("mode", "docker"), port, base, spec, st.get("container"), reused=True)
        stop(slug)                                  # an instance of an older approval is still up: replace it
    mode = choose_mode(entry)
    source = pathlib.Path(source_dir).resolve() if source_dir else clone
    key = container_name(slug, instance)
    container = None
    if mode == "docker":
        container = _start_docker(slug, spec, source, port, token, instance)
    else:
        _start_process(slug, spec, source, port, token, key)
    if not instance:
        _save_state(slug, {**_state(slug), "mode": mode, "container": container, "started_at": time.time(), "fingerprint": entry.approved_fingerprint,
                           "pid": _PROCS[key].pid if key in _PROCS else None})
    return Running(slug, mode, port, base, spec, container)

def stop(slug: str, instance: str | None = None) -> None:
    key = container_name(slug, instance)
    proc = _PROCS.pop(key, None)
    if proc is not None and proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(5)
        except subprocess.TimeoutExpired:
            proc.kill()
    if shutil.which("docker"):
        try:
            _docker(["docker", "rm", "-f", key], 30)
        except Exception:
            pass
    if not instance:
        st = _state(slug)
        if st:
            _save_state(slug, {k: v for k, v in st.items() if k in ("port", "token")})

def purge(slug: str) -> None:
    """stop() plus the built image; used when a target is removed."""
    stop(slug)
    if shutil.which("docker"):
        try:
            _docker(["docker", "rmi", "-f", image_name(slug)], 60)
        except Exception:
            pass

def status(slug: str) -> dict:
    """Cheap, never raises: what the UI shows next to a target."""
    st = _state(slug)
    running = bool(st.get("port") and st.get("token") and st.get("mode") and _is_ours(st["port"], st["token"]))
    return {"running": running, "mode": st.get("mode") if running else None, "port": st.get("port") if running else None,
            "container": st.get("container") if running else None, "docker_available": docker_available()}
